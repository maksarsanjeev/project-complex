import type { ToolDef } from './types.ts'

/**
 * Конец итерации — не движок, а разговор.
 *
 * Появился из наблюдения: модель, оставленная одна, полирует бесконечно. За
 * один заход она сделала двадцать четыре круга доводки и ни разу не решила,
 * что закончила, — всегда находился зазор в 0,001 мм³ на углу прилива. Планка
 * «готово» у неё внутренняя и дна не имеет, а должна быть человеческой.
 *
 * Поэтому проход заканчивается вызовом этого инструмента: модель показывает
 * сделанное и ждёт. Человек смотрит во вьюпорт и решает — продолжать, оставить
 * как есть или сказать своими словами.
 *
 * Инструмент не единственный спусковой крючок: если модель им не
 * воспользуется, чекпойнт сработает сам, как только в сцене появится
 * геометрия. Полагаться на её дисциплину в длинном ходе нельзя — она плывёт.
 */
export const ITERATION_TOOL: ToolDef = {
  name: 'iteration_done',
  engine: 'rhino',
  command: 'iteration_done',
  description:
    'Заверши проход и покажи результат человеку. Вызывай, КАК ТОЛЬКО собрана цельная вещь, ' +
    'пригодная к сдаче, — не полируй по своей инициативе. Ход на этом кончается: модель ' +
    'подтянется во вьюпорт, человек посмотрит и скажет, продолжать ли. Не спрашивай ' +
    'разрешения текстом — вызывай этот инструмент.',
  parameters: {
    type: 'object',
    properties: {
      done: {
        type: 'string',
        description: 'Что сделано за этот проход — коротко, по делу, без похвал себе.',
      },
      weak: {
        type: 'string',
        description:
          'Что сам считаешь слабым и что предлагаешь доделать следующим проходом. Честно: ' +
          'человек решает по этому списку, стоит ли продолжать.',
      },
    },
    required: ['done'],
  },
}

export const ITERATION_TOOL_NAME = ITERATION_TOOL.name
