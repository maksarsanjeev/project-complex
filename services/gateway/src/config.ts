import { resolve } from 'node:path'

/**
 * Настройки берутся только из окружения. Значения по умолчанию рассчитаны на
 * локальный запуск; на виртуалке всё задаётся в /opt/complex/.env, который в
 * репозиторий не попадает.
 */
export const config = {
  /** Порт, на котором gateway слушает и HTTP, и веб-сокет. */
  port: Number(process.env.PORT ?? 8787),

  /** Файл базы. В контейнере это том, чтобы данные пережили пересборку. */
  dbPath: resolve(process.env.DB_PATH ?? './data/complex.db'),

  /**
   * Каталог собранного фронтенда. Тот же контейнер раздаёт и приложение, и API,
   * чтобы всё открывалось по одному адресу.
   */
  webRoot: process.env.WEB_ROOT ? resolve(process.env.WEB_ROOT) : null,

  /** Ключ OpenRouter. Пока пуст — чат отвечает заглушкой. */
  openRouterKey: process.env.OPENROUTER_API_KEY ?? '',

  /**
   * Вход для Claude Agent SDK — второй провайдер модели, тот же движок, что у
   * Claude Code.
   *
   * Две переменные, и разница между ними не только техническая.
   * `CLAUDE_CODE_OAUTH_TOKEN` — вход по подписке, его выдаёт `claude setup-token`
   * на машине, где вы уже вошли. Документация Agent SDK разрешает подписочный
   * вход не для всякого применения: сторонним продуктам предписан ключ API.
   * Поэтому для личного запуска годится первое, а для всего, что раздаётся
   * другим людям, — `ANTHROPIC_API_KEY`.
   *
   * Мы не выбираем за пользователя: берём то, что задано, и если не задано
   * ничего — провайдер помечается ненастроенным, а чат говорит об этом прямо.
   */
  claudeCodeToken: process.env.CLAUDE_CODE_OAUTH_TOKEN ?? '',
  anthropicKey: process.env.ANTHROPIC_API_KEY ?? '',

  /**
   * Модель по умолчанию. Sonnet 5 — миллион контекста за $2/$10 на миллион
   * токенов: дешевле прежнего Sonnet 4.5 и новее его. Тяжёлые задачи по
   * геометрии имеет смысл гонять на Opus 5, он выбирается в интерфейсе.
   */
  defaultModel: process.env.DEFAULT_MODEL ?? 'anthropic/claude-sonnet-5',

  /**
   * Пропуск для агентов с рабочих машин. Пустой — агенты не пускаются вовсе.
   *
   * Закрыто по умолчанию намеренно: gateway слушает на всю локальную сеть, а
   * через агента исполняется произвольный код в SketchUp, Rhino и Blender.
   * Забыть выставить токен должно означать «никто не подключится», а не
   * «подключится кто угодно».
   */
  agentToken: process.env.AGENT_TOKEN ?? '',

  /**
   * Сколько кругов «модель просит инструмент → выполняем → отдаём результат»
   * разрешено на один ход пользователя. Ограничение спасает от зацикливания,
   * когда модель упорно повторяет неудачный вызов.
   *
   * Восьми не хватает на сложную форму: на шуруповёрте модель посмотрела на
   * результат, нашла у себя ошибку — «курок висит в воздухе» — и оборвалась
   * посреди исправления. Цикл «построил → посмотрел → поправил» требует кругов
   * втрое больше, чем простая постройка.
   */
  maxToolRounds: Number(process.env.MAX_TOOL_ROUNDS ?? 20),

  /**
   * Потолок кругов на пути Agent SDK — страховка от зацикливания, не бюджет.
   *
   * Держится высоко намеренно. Двадцати кругов не хватило на шуруповёрт в
   * Rhino: модель сама увидела, что корпус не попал в документ, докопалась до
   * причины и полезла чинить — и её срезало посреди починки. Ограничивать
   * работу должен расход (`tokenBudget`), который человек может снять, а не
   * счётчик, о котором он не знает.
   */
  cliMaxTurns: Number(process.env.CLI_MAX_TURNS ?? 200),

  /**
   * Сколько токенов ход тратит, прежде чем спросить разрешения продолжить.
   *
   * Считается всё вместе — ввод (включая чтение из кэша) и ответ, ровно та
   * цифра, что печатается в логе расхода. Кэш делает токены дешевле, но не
   * бесплатнее: на подписке они одинаково расходуют лимит.
   *
   * Предел не обрывает работу, а превращается в вопрос: модель останавливается
   * и спрашивает, продолжать ли. Ответ человека — обычное следующее сообщение,
   * а сессия SDK продолжается с того же места, так что согласие не стоит
   * ничего сверх нового бюджета. Ноль снимает предел вовсе.
   */
  tokenBudget: Number(process.env.TOKEN_BUDGET ?? 1_000_000),

  /**
   * Какой мост к Rhino считается основным.
   *
   * Оба плагина стоят в одном Rhino и оба работают, но публиковать модели сразу
   *два набора инструментов вредно: она смешивает их в одном ходе и путается, а
   * описания стоят токенов на каждом круге. Основной — McNeel: канал чище
   * (один конверт вместо двойной печати) и Python третий вместо IronPython 2,
   * на котором прошлые сборки теряли круги на борьбе с самим движком.
   *
   * `both` оставлен для сравнений вроде того, которым этот выбор и сделан.
   */
  rhinoBridge: (process.env.RHINO_BRIDGE ?? 'mcneel') as 'mcneel' | 'jingcheng' | 'both',

  /**
   * Пока нет входа, всё принадлежит одному пользователю. Схема базы при этом
   * многопользовательская с первого дня: добавить вход = добавить строки в
   * users и выдавать настоящий идентификатор, а не переписывать все запросы.
   */
  singleUserId: 'u-local',
} as const

export type Config = typeof config
