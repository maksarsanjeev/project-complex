import { resolve } from 'node:path'

/**
 * Настройки берутся только из окружения. Значения по умолчанию рассчитаны на
 * локальный запуск; на виртуалке всё задаётся в /opt/complex/.env, который в
 * репозиторий не попадает.
 */
export const config = {
  /** Порт, на котором gateway слушает и HTTP, и веб-сокет. */
  port: Number(process.env.PORT ?? 8787),

  /** Файл базы. В контейнере это том, чтобы данные пережили пересборку. */
  dbPath: resolve(process.env.DB_PATH ?? './data/complex.db'),

  /**
   * Каталог собранного фронтенда. Тот же контейнер раздаёт и приложение, и API,
   * чтобы всё открывалось по одному адресу.
   */
  webRoot: process.env.WEB_ROOT ? resolve(process.env.WEB_ROOT) : null,

  /** Ключ OpenRouter. Пока пуст — чат отвечает заглушкой. */
  openRouterKey: process.env.OPENROUTER_API_KEY ?? '',

  /**
   * Модель по умолчанию. Sonnet 5 — миллион контекста за $2/$10 на миллион
   * токенов: дешевле прежнего Sonnet 4.5 и новее его. Тяжёлые задачи по
   * геометрии имеет смысл гонять на Opus 5, он выбирается в интерфейсе.
   */
  defaultModel: process.env.DEFAULT_MODEL ?? 'anthropic/claude-sonnet-5',

  /**
   * Пропуск для агентов с рабочих машин. Пустой — агенты не пускаются вовсе.
   *
   * Закрыто по умолчанию намеренно: gateway слушает на всю локальную сеть, а
   * через агента исполняется произвольный код в SketchUp, Rhino и Blender.
   * Забыть выставить токен должно означать «никто не подключится», а не
   * «подключится кто угодно».
   */
  agentToken: process.env.AGENT_TOKEN ?? '',

  /**
   * Сколько кругов «модель просит инструмент → выполняем → отдаём результат»
   * разрешено на один ход пользователя. Ограничение спасает от зацикливания,
   * когда модель упорно повторяет неудачный вызов.
   *
   * Восьми не хватает на сложную форму: на шуруповёрте модель посмотрела на
   * результат, нашла у себя ошибку — «курок висит в воздухе» — и оборвалась
   * посреди исправления. Цикл «построил → посмотрел → поправил» требует кругов
   * втрое больше, чем простая постройка.
   */
  maxToolRounds: Number(process.env.MAX_TOOL_ROUNDS ?? 20),

  /**
   * Пока нет входа, всё принадлежит одному пользователю. Схема базы при этом
   * многопользовательская с первого дня: добавить вход = добавить строки в
   * users и выдавать настоящий идентификатор, а не переписывать все запросы.
   */
  singleUserId: 'u-local',
} as const

export type Config = typeof config
